-- ============================================================
-- 超级管理员角色迁移示例
-- 适用场景：启用后台用户管理前，将指定管理员账号提升为超级管理员。
-- 注意：请把 your_admin_account 替换为真实账号后再执行。
-- ============================================================

UPDATE `user`
SET `role` = 2
WHERE `user_account` = 'your_admin_account'
  AND `deleted` = 0;
